/**
 * Bundles the Express API (backend/src) into one ESM file for Supabase Edge
 * Functions (Deno):  supabase/functions/api/bikripro.js
 *
 * - Local source files are bundled; npm packages stay external and are
 *   rewritten to versioned `npm:` specifiers that the Edge Runtime installs.
 * - Node-only extras are replaced: sharp (images are resized in the app),
 *   node-cron (Supabase pg_cron calls /api/cron/birthdays) and dotenv.
 *
 * Run:  npm run build:edge   (from backend/)
 */
import { build } from 'esbuild';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const backend = path.resolve(here, '..');
const outfile = path.resolve(backend, '../supabase/functions/api/bikripro.js');
const lock = JSON.parse(readFileSync(path.join(backend, 'package-lock.json'), 'utf8'));
const version = (name) => lock.packages[`node_modules/${name}`]?.version;

const STUBS = {
  sharp: 'export default null;',
  'node-cron': 'export default { schedule() {}, validate() { return false; } };',
  dotenv: 'export default { config() { return {}; } };',
};

const edgePlugin = {
  name: 'bikripro-edge',
  setup(b) {
    b.onResolve({ filter: /^[^./]/ }, (args) => {
      if (args.path.startsWith('node:')) return { path: args.path, external: true };
      const name = args.path.startsWith('@') ? args.path.split('/').slice(0, 2).join('/') : args.path.split('/')[0];
      if (STUBS[name]) return { path: name, namespace: 'stub' };
      const v = version(name);
      if (!v) throw new Error(`No locked version for ${name}`);
      return { path: `npm:${name}@${v}${args.path.slice(name.length)}`, external: true };
    });
    b.onLoad({ filter: /.*/, namespace: 'stub' }, (args) => ({ contents: STUBS[args.path], loader: 'js' }));
  },
};

await build({
  entryPoints: [path.join(backend, 'src/app.js')],
  outfile,
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  minify: true,
  legalComments: 'none',
  banner: { js: '// Generated by backend/scripts/build-edge.mjs — do not edit. Source: backend/src' },
  plugins: [edgePlugin],
  logLevel: 'info',
});
