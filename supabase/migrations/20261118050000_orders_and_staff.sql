-- =====================================================================
-- Purchase orders (to suppliers) and staff: employees, attendance,
-- salary, advances, commission & targets. Idempotent.
-- =====================================================================

-- ---------------------------------------------------------------------
-- Purchase orders
-- ---------------------------------------------------------------------
create table if not exists public.purchase_orders (
  id            bigint generated by default as identity primary key,
  po_no         text not null unique,
  supplier_id   bigint not null references public.suppliers(id) deferrable initially immediate,
  status        text not null default 'draft' check (status in ('draft','sent','partial','received','cancelled')),
  order_date    date not null default public.bp_today(),
  expected_date date,
  note          text,
  total         numeric(14,2) not null default 0,
  created_by    bigint references public.users(id) on delete set null deferrable initially immediate,
  created_at    timestamp(0) not null default public.bp_now(),
  updated_at    timestamp(0) not null default public.bp_now()
);
create index if not exists idx_po_supplier on public.purchase_orders (supplier_id);
create index if not exists idx_po_status on public.purchase_orders (status, order_date);
create index if not exists idx_po_created_by on public.purchase_orders (created_by);

create table if not exists public.purchase_order_items (
  id           bigint generated by default as identity primary key,
  po_id        bigint not null references public.purchase_orders(id) on delete cascade deferrable initially immediate,
  variant_id   bigint not null references public.product_variants(id) deferrable initially immediate,
  qty          numeric(12,2) not null check (qty > 0),
  unit_cost    numeric(14,2) not null default 0,
  received_qty numeric(12,2) not null default 0
);
create index if not exists idx_poi_po on public.purchase_order_items (po_id);
create index if not exists idx_poi_variant on public.purchase_order_items (variant_id);

alter table public.purchases add column if not exists po_id bigint references public.purchase_orders(id) on delete set null deferrable initially immediate;
create index if not exists idx_purchases_po on public.purchases (po_id);

-- ---------------------------------------------------------------------
-- Staff
-- ---------------------------------------------------------------------
create table if not exists public.employees (
  id                 bigint generated by default as identity primary key,
  name               text not null,
  phone              text,
  designation        text,
  user_id            bigint unique references public.users(id) on delete set null deferrable initially immediate, -- login, if any
  join_date          date,
  monthly_salary     numeric(14,2) not null default 0,
  commission_percent numeric(6,2) not null default 0,   -- % of own net sales
  monthly_target     numeric(14,2) not null default 0,   -- sales target per month
  is_active          boolean not null default true,
  note               text,
  created_at         timestamp(0) not null default public.bp_now()
);

create table if not exists public.attendance (
  id          bigint generated by default as identity primary key,
  employee_id bigint not null references public.employees(id) on delete cascade deferrable initially immediate,
  att_date    date not null,
  status      text not null check (status in ('present','absent','leave','half','off')),
  in_time     time,
  out_time    time,
  note        text,
  unique (employee_id, att_date)
);
create index if not exists idx_attendance_date on public.attendance (att_date);

create table if not exists public.employee_advances (
  id           bigint generated by default as identity primary key,
  employee_id  bigint not null references public.employees(id) deferrable initially immediate,
  amount       numeric(14,2) not null check (amount > 0),
  adv_date     date not null default public.bp_today(),
  account_id   bigint not null references public.accounts(id) deferrable initially immediate,
  note         text,
  salary_payment_id bigint,          -- set when recovered from a salary
  user_id      bigint references public.users(id) on delete set null deferrable initially immediate,
  created_at   timestamp(0) not null default public.bp_now()
);
create index if not exists idx_adv_employee on public.employee_advances (employee_id);
create index if not exists idx_adv_account on public.employee_advances (account_id);
create index if not exists idx_adv_user on public.employee_advances (user_id);

create table if not exists public.salary_payments (
  id            bigint generated by default as identity primary key,
  employee_id   bigint not null references public.employees(id) deferrable initially immediate,
  month         text not null check (month ~ '^\d{4}-\d{2}$'),
  basic         numeric(14,2) not null default 0,
  commission    numeric(14,2) not null default 0,
  bonus         numeric(14,2) not null default 0,
  deduction     numeric(14,2) not null default 0,   -- absence or other cuts
  advance_recovered numeric(14,2) not null default 0,
  gross         numeric(14,2) not null default 0,   -- basic + commission + bonus - deduction (the expense)
  net_paid      numeric(14,2) not null default 0,   -- gross - advance recovered (cash out)
  account_id    bigint not null references public.accounts(id) deferrable initially immediate,
  expense_id    bigint references public.expenses(id) on delete set null deferrable initially immediate,
  paid_date     date not null default public.bp_today(),
  note          text,
  user_id       bigint references public.users(id) on delete set null deferrable initially immediate,
  created_at    timestamp(0) not null default public.bp_now(),
  unique (employee_id, month)
);
create index if not exists idx_salary_account on public.salary_payments (account_id);
create index if not exists idx_salary_expense on public.salary_payments (expense_id);
create index if not exists idx_salary_user on public.salary_payments (user_id);

do $$ begin
  if not exists (select 1 from pg_constraint where conname = 'employee_advances_salary_fk') then
    alter table public.employee_advances add constraint employee_advances_salary_fk
      foreign key (salary_payment_id) references public.salary_payments(id) on delete set null deferrable initially immediate;
  end if;
end $$;
create index if not exists idx_adv_salary on public.employee_advances (salary_payment_id);

-- Sales person on an invoice (floor staff who served the customer)
alter table public.sales add column if not exists salesperson_id bigint references public.employees(id) on delete set null deferrable initially immediate;
create index if not exists idx_sales_salesperson on public.sales (salesperson_id, sale_date);

-- Money for staff advances leaves the cash drawer too
alter table public.account_transactions drop constraint if exists account_transactions_ref_type_check;
alter table public.account_transactions add constraint account_transactions_ref_type_check
  check (ref_type in ('sale','sale_return','purchase','purchase_return','collection','supplier_payment','expense','transfer','deposit','withdraw','opening','staff_advance'));

do $$
declare t text;
begin
  foreach t in array array['purchase_orders','purchase_order_items','employees','attendance','employee_advances','salary_payments'] loop
    execute format('alter table public.%I enable row level security', t);
    if exists (select 1 from pg_roles where rolname = 'anon') then
      execute format('revoke all on public.%I from anon, authenticated', t);
    end if;
  end loop;
end $$;
