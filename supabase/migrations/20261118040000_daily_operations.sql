-- =====================================================================
-- Daily operations: cash drawer shifts (day closing), exchanges, offers,
-- stock count / audit, damage & lost stock, shareable receipt links.
-- Idempotent — safe to run on every start.
-- =====================================================================

-- ---------------------------------------------------------------------
-- Cash drawer shifts (Day closing)
-- ---------------------------------------------------------------------
create table if not exists public.cash_sessions (
  id            bigint generated by default as identity primary key,
  session_no    text not null unique,
  user_id       bigint not null references public.users(id) deferrable initially immediate,
  account_id    bigint not null references public.accounts(id) deferrable initially immediate,
  opened_at     timestamp(0) not null default public.bp_now(),
  opening_cash  numeric(14,2) not null default 0,
  closed_at     timestamp(0),
  closed_by     bigint references public.users(id) on delete set null deferrable initially immediate,
  cash_in       numeric(14,2),            -- snapshot at closing
  cash_out      numeric(14,2),
  expected_cash numeric(14,2),
  counted_cash  numeric(14,2),
  variance      numeric(14,2),            -- counted - expected (minus = short)
  denominations jsonb,                    -- {"1000": 3, "500": 2, ...}
  opening_note  text,
  closing_note  text,
  status        text not null default 'open' check (status in ('open','closed'))
);
create index if not exists idx_cash_sessions_user on public.cash_sessions (user_id, opened_at);
create index if not exists idx_cash_sessions_account on public.cash_sessions (account_id);
create index if not exists idx_cash_sessions_closed_by on public.cash_sessions (closed_by);
-- One open shift per cashier
create unique index if not exists uq_cash_sessions_open on public.cash_sessions (user_id) where status = 'open';

-- ---------------------------------------------------------------------
-- Offers & discounts
-- ---------------------------------------------------------------------
create table if not exists public.offers (
  id          bigint generated by default as identity primary key,
  name        text not null,
  type        text not null check (type in ('percent','amount','bogo','bill_percent','bill_amount')),
  value       numeric(14,2) not null default 0,     -- % or Tk off
  buy_qty     integer not null default 0,           -- bogo: buy X …
  get_qty     integer not null default 0,           -- … get Y free
  scope       text not null default 'all' check (scope in ('all','category','brand','product')),
  scope_ids   bigint[] not null default '{}',
  min_amount  numeric(14,2) not null default 0,     -- bill offers: minimum bill
  max_discount numeric(14,2),                       -- optional cap per bill
  starts_on   date,
  ends_on     date,
  is_active   boolean not null default true,
  note        text,
  created_by  bigint references public.users(id) on delete set null deferrable initially immediate,
  created_at  timestamp(0) not null default public.bp_now()
);
create index if not exists idx_offers_active on public.offers (is_active, starts_on, ends_on);
create index if not exists idx_offers_created_by on public.offers (created_by);

alter table public.sale_items add column if not exists offer_id bigint references public.offers(id) on delete set null deferrable initially immediate;
alter table public.sale_items add column if not exists offer_discount numeric(14,2) not null default 0;
create index if not exists idx_si_offer on public.sale_items (offer_id);
alter table public.sales add column if not exists bill_offer_id bigint references public.offers(id) on delete set null deferrable initially immediate;
alter table public.sales add column if not exists offer_discount numeric(14,2) not null default 0;
create index if not exists idx_sales_bill_offer on public.sales (bill_offer_id);

-- ---------------------------------------------------------------------
-- Exchange (return + new sale on one receipt)
-- ---------------------------------------------------------------------
alter table public.sales add column if not exists exchange_credit numeric(14,2) not null default 0;
alter table public.sales add column if not exists exchange_return_id bigint references public.sale_returns(id) on delete set null deferrable initially immediate;
create index if not exists idx_sales_exchange_return on public.sales (exchange_return_id);
alter table public.sale_returns add column if not exists exchange_credit numeric(14,2) not null default 0;  -- part of refund_amount used on the new sale
alter table public.sale_returns add column if not exists exchange_sale_id bigint references public.sales(id) on delete set null deferrable initially immediate;
create index if not exists idx_sr_exchange_sale on public.sale_returns (exchange_sale_id);

-- ---------------------------------------------------------------------
-- Shareable receipt link
-- ---------------------------------------------------------------------
alter table public.sales add column if not exists public_token text;
create unique index if not exists uq_sales_public_token on public.sales (public_token) where public_token is not null;

-- ---------------------------------------------------------------------
-- Stock adjustments (damage, lost, theft, count corrections …)
-- ---------------------------------------------------------------------
create table if not exists public.stock_adjustments (
  id          bigint generated by default as identity primary key,
  adj_no      text not null,
  variant_id  bigint not null references public.product_variants(id) deferrable initially immediate,
  qty_change  numeric(12,2) not null,                -- minus = stock out
  reason      text not null check (reason in ('damage','lost','theft','expired','count','found','gift','other')),
  unit_cost   numeric(14,2) not null default 0,
  value       numeric(14,2) not null default 0,      -- qty_change * unit_cost (minus = loss)
  note        text,
  ref_type    text not null default 'manual' check (ref_type in ('manual','stock_count')),
  ref_id      bigint,
  adj_date    date not null default public.bp_today(),
  user_id     bigint references public.users(id) on delete set null deferrable initially immediate,
  created_at  timestamp(0) not null default public.bp_now()
);
create index if not exists idx_stock_adj_variant on public.stock_adjustments (variant_id);
create index if not exists idx_stock_adj_date on public.stock_adjustments (adj_date);
create index if not exists idx_stock_adj_user on public.stock_adjustments (user_id);
create index if not exists idx_stock_adj_ref on public.stock_adjustments (ref_type, ref_id);

-- ---------------------------------------------------------------------
-- Stock count / audit
-- ---------------------------------------------------------------------
create table if not exists public.stock_counts (
  id          bigint generated by default as identity primary key,
  count_no    text not null unique,
  title       text,
  status      text not null default 'draft' check (status in ('draft','applied','cancelled')),
  note        text,
  created_by  bigint references public.users(id) on delete set null deferrable initially immediate,
  created_at  timestamp(0) not null default public.bp_now(),
  applied_by  bigint references public.users(id) on delete set null deferrable initially immediate,
  applied_at  timestamp(0)
);
create index if not exists idx_stock_counts_created_by on public.stock_counts (created_by);
create index if not exists idx_stock_counts_applied_by on public.stock_counts (applied_by);

create table if not exists public.stock_count_items (
  id          bigint generated by default as identity primary key,
  count_id    bigint not null references public.stock_counts(id) on delete cascade deferrable initially immediate,
  variant_id  bigint not null references public.product_variants(id) deferrable initially immediate,
  counted_qty numeric(12,2),            -- null = not counted yet
  system_qty  numeric(12,2),            -- stock at the moment the count was applied
  updated_at  timestamp(0) not null default public.bp_now(),
  unique (count_id, variant_id)
);
create index if not exists idx_sci_variant on public.stock_count_items (variant_id);

-- ---------------------------------------------------------------------
-- Customer balance: exchange credit is part of refund_amount, so the view is unchanged.
-- Lock the Data API out of the new tables.
-- ---------------------------------------------------------------------
do $$
declare t text;
begin
  foreach t in array array['cash_sessions','offers','stock_adjustments','stock_counts','stock_count_items'] loop
    execute format('alter table public.%I enable row level security', t);
    if exists (select 1 from pg_roles where rolname = 'anon') then
      execute format('revoke all on public.%I from anon, authenticated', t);
    end if;
  end loop;
end $$;

