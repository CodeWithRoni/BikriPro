-- =====================================================================
-- Product Setup: sub-categories, unit types, colours, sizes and
-- variation sets (e.g. "Shirt sizes" → S, M, L, XL).
-- Idempotent — safe to run on every start.
-- =====================================================================

-- Sub-categories live in categories.parent_id. The same sub-category name may
-- appear under different parents ("Formal" under Shirt and under Pant), so the
-- global unique name becomes unique per parent (case-insensitive).
alter table public.categories drop constraint if exists categories_name_key;
create unique index if not exists uq_categories_parent_name
  on public.categories (coalesce(parent_id, 0), lower(name));

create table if not exists public.product_attributes (
  id         bigint generated by default as identity primary key,
  kind       text not null check (kind in ('unit', 'color', 'size', 'variation')),
  name       text not null,
  value      text,            -- unit: short code (pcs) · color: #hex · variation: comma-separated values
  sort_order integer not null default 0,
  created_at timestamp(0) not null default public.bp_now()
);
create unique index if not exists uq_product_attributes_kind_name
  on public.product_attributes (kind, lower(name));
create index if not exists idx_product_attributes_kind_sort
  on public.product_attributes (kind, sort_order, id);

-- Faster product filters by size / colour / price
create index if not exists idx_variants_size on public.product_variants (size);
create index if not exists idx_variants_color on public.product_variants (color);

-- Lock the Data API out (same as every other table)
do $$
begin
  execute 'alter table public.product_attributes enable row level security';
  if exists (select 1 from pg_roles where rolname = 'anon') then
    execute 'revoke all on public.product_attributes from anon, authenticated';
  end if;
end $$;

