-- =====================================================================
-- BikriPro POS & ERP — PostgreSQL schema (Supabase / Postgres 15+)
-- Garments & clothing retail. Money = numeric(14,2) BDT.
-- Times are stored as Bangladesh local time (Asia/Dhaka) in timestamp(0)
-- columns via bp_now()/bp_today(), so reports are correct no matter which
-- timezone the database server or connection pooler uses.
--
-- Security model: the BikriPro API server connects as the table owner and
-- does all authorisation itself (JWT roles). Every table has RLS enabled with
-- NO policies, and anon/authenticated are revoked, so Supabase publishable /
-- anon keys can never read or write shop data through the Data API.
-- Idempotent: safe to run on every server start.
-- =====================================================================

-- ---------- helpers ----------
create or replace function public.bp_now() returns timestamp
  language sql stable set search_path = ''
  as $$ select (now() at time zone 'Asia/Dhaka')::timestamp(0) $$;

create or replace function public.bp_today() returns date
  language sql stable set search_path = ''
  as $$ select (now() at time zone 'Asia/Dhaka')::date $$;

create or replace function public.bp_set_updated_at() returns trigger
  language plpgsql set search_path = ''
  as $$ begin new.updated_at := public.bp_now(); return new; end $$;

