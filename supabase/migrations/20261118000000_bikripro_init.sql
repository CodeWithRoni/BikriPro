-- ---------------------------------------------------------------------
-- updated_at triggers
-- ---------------------------------------------------------------------
do $$
declare t text;
begin
  foreach t in array array['users','products','product_variants','customers','suppliers'] loop
    execute format('drop trigger if exists trg_%1$s_updated on public.%1$I', t);
    execute format('create trigger trg_%1$s_updated before update on public.%1$I for each row execute function public.bp_set_updated_at()', t);
  end loop;
end $$;

-- ---------------------------------------------------------------------
-- Balance views (security_invoker so they never bypass RLS)
-- ---------------------------------------------------------------------
create or replace view public.v_customer_balance with (security_invoker = true) as
select c.id as customer_id,
  c.opening_balance
  + coalesce((select sum(s.grand_total - s.paid_amount) from public.sales s where s.customer_id = c.id and s.status <> 'cancelled'), 0)
  - coalesce((select sum(r.total_amount - r.refund_amount) from public.sale_returns r where r.customer_id = c.id), 0)
  - coalesce((select sum(cc.amount) from public.customer_collections cc where cc.customer_id = c.id), 0)
  + coalesce((select sum(case when a.effect = 'addition' then a.amount else -a.amount end)
              from public.ledger_adjustments a where a.party_type = 'customer' and a.party_id = c.id), 0)
  as balance
from public.customers c;

create or replace view public.v_supplier_balance with (security_invoker = true) as
select sp.id as supplier_id,
  sp.opening_balance
  + coalesce((select sum(p.grand_total - p.paid_amount) from public.purchases p where p.supplier_id = sp.id), 0)
  - coalesce((select sum(r.total_amount - r.refund_amount) from public.purchase_returns r where r.supplier_id = sp.id), 0)
  - coalesce((select sum(x.amount) from public.supplier_payments x where x.supplier_id = sp.id), 0)
  + coalesce((select sum(case when a.effect = 'addition' then a.amount else -a.amount end)
              from public.ledger_adjustments a where a.party_type = 'supplier' and a.party_id = sp.id), 0)
  as balance
from public.suppliers sp;

-- ---------------------------------------------------------------------
-- Lock the Data API out: RLS on (no policies) + revoke API roles
-- ---------------------------------------------------------------------
do $$
declare t text;
begin
  for t in select tablename from pg_tables where schemaname = 'public' and tablename in (
    'users','settings','number_sequences','activity_logs','accounts','account_transactions','categories','brands',
    'products','product_variants','price_history','customers','customer_contacts','suppliers','supplier_contacts',
    'ledger_adjustments','sales','sale_items','sale_payments','held_invoices','sale_returns','sale_return_items',
    'purchases','purchase_items','purchase_payments','purchase_returns','purchase_return_items','supplier_payments',
    'customer_collections','expense_categories','expenses','loyalty_transactions','sms_logs')
  loop
    execute format('alter table public.%I enable row level security', t);
    if exists (select 1 from pg_roles where rolname = 'anon') then
      execute format('revoke all on public.%I from anon, authenticated', t);
    end if;
  end loop;
  if exists (select 1 from pg_roles where rolname = 'anon') then
    revoke all on public.v_customer_balance, public.v_supplier_balance from anon, authenticated;
    revoke execute on function public.bp_now(), public.bp_today(), public.bp_set_updated_at() from anon, authenticated, public;
  end if;
end $$;
