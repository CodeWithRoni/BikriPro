-- =====================================================================
-- Online orders (Facebook / website / phone …) with courier & COD tracking,
-- plus a delivery charge on sales. Idempotent.
-- =====================================================================

alter table public.sales add column if not exists delivery_charge numeric(14,2) not null default 0;

create table if not exists public.online_orders (
  id               bigint generated by default as identity primary key,
  order_no         text not null unique,
  source           text not null default 'facebook' check (source in ('facebook','instagram','website','whatsapp','phone','daraz','other')),
  customer_id      bigint references public.customers(id) on delete set null deferrable initially immediate,
  customer_name    text not null,
  phone            text not null,
  address          text,
  area             text,
  note             text,
  subtotal         numeric(14,2) not null default 0,
  discount         numeric(14,2) not null default 0,
  delivery_charge  numeric(14,2) not null default 0,   -- charged to the customer
  total            numeric(14,2) not null default 0,
  advance_paid     numeric(14,2) not null default 0,
  advance_account_id bigint references public.accounts(id) deferrable initially immediate,
  advance_ref      text,
  status           text not null default 'new' check (status in ('new','confirmed','packed','shipped','delivered','returned','cancelled')),
  courier          text check (courier in ('pathao','steadfast','redx','paperfly','sundarban','ecourier','own','other')),
  tracking_no      text,
  courier_charge   numeric(14,2) not null default 0,   -- the shop's cost
  cod_amount       numeric(14,2) not null default 0,   -- to collect at the door
  cod_status       text not null default 'none' check (cod_status in ('none','pending','settled')),
  settled_amount   numeric(14,2) not null default 0,
  settled_at       timestamp(0),
  settle_account_id bigint references public.accounts(id) deferrable initially immediate,
  sale_id          bigint references public.sales(id) on delete set null deferrable initially immediate,
  return_id        bigint references public.sale_returns(id) on delete set null deferrable initially immediate,
  shipped_at       timestamp(0),
  delivered_at     timestamp(0),
  branch_id        bigint references public.branches(id) deferrable initially immediate,
  created_by       bigint references public.users(id) on delete set null deferrable initially immediate,
  created_at       timestamp(0) not null default public.bp_now(),
  updated_at       timestamp(0) not null default public.bp_now()
);
create index if not exists idx_oo_status on public.online_orders (status, created_at);
create index if not exists idx_oo_phone on public.online_orders (phone);
create index if not exists idx_oo_customer on public.online_orders (customer_id);
create index if not exists idx_oo_sale on public.online_orders (sale_id);
create index if not exists idx_oo_return on public.online_orders (return_id);
create index if not exists idx_oo_branch on public.online_orders (branch_id);
create index if not exists idx_oo_created_by on public.online_orders (created_by);
create index if not exists idx_oo_adv_acc on public.online_orders (advance_account_id);
create index if not exists idx_oo_settle_acc on public.online_orders (settle_account_id);
drop trigger if exists trg_online_orders_branch on public.online_orders;
create trigger trg_online_orders_branch before insert on public.online_orders for each row execute function public.bp_set_branch();

create table if not exists public.online_order_items (
  id          bigint generated by default as identity primary key,
  order_id    bigint not null references public.online_orders(id) on delete cascade deferrable initially immediate,
  variant_id  bigint not null references public.product_variants(id) deferrable initially immediate,
  qty         numeric(12,2) not null check (qty > 0),
  unit_price  numeric(14,2) not null,
  discount    numeric(14,2) not null default 0
);
create index if not exists idx_ooi_order on public.online_order_items (order_id);
create index if not exists idx_ooi_variant on public.online_order_items (variant_id);

do $$
declare t text;
begin
  foreach t in array array['online_orders','online_order_items'] loop
    execute format('alter table public.%I enable row level security', t);
    if exists (select 1 from pg_roles where rolname = 'anon') then
      execute format('revoke all on public.%I from anon, authenticated', t);
    end if;
  end loop;
end $$;

