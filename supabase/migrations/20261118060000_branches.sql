-- =====================================================================
-- Multi-branch: branches, per-branch stock, stock transfers, and a
-- branch_id on every branch-level record. Idempotent.
--
-- How the API uses it: each request runs with a "current branch". Inside a
-- transaction the API sets bikripro.branch_id, and a BEFORE INSERT trigger
-- fills branch_id on new rows. product_variants.stock_qty stays the total of
-- all branches (plus goods in transit); branch_stock holds each branch's part.
-- =====================================================================

create table if not exists public.branches (
  id         bigint generated by default as identity primary key,
  name       text not null unique,
  code       text,
  address    text,
  phone      text,
  is_main    boolean not null default false,
  is_active  boolean not null default true,
  created_at timestamp(0) not null default public.bp_now()
);
create unique index if not exists uq_branches_main on public.branches (is_main) where is_main;
insert into public.branches (name, code, is_main)
select 'Main Branch', 'MAIN', true where not exists (select 1 from public.branches);

create or replace function public.bp_main_branch() returns bigint
language sql stable set search_path = public, pg_temp as $$
  select id from public.branches order by is_main desc, id limit 1
$$;

create or replace function public.bp_branch() returns bigint
language sql stable set search_path = public, pg_temp as $$
  select coalesce(nullif(current_setting('bikripro.branch_id', true), '')::bigint, public.bp_main_branch())
$$;

-- ---------------------------------------------------------------------
-- Per-branch stock
-- ---------------------------------------------------------------------
create table if not exists public.branch_stock (
  branch_id  bigint not null references public.branches(id) on delete cascade deferrable initially immediate,
  variant_id bigint not null references public.product_variants(id) on delete cascade deferrable initially immediate,
  qty        numeric(12,2) not null default 0,
  primary key (branch_id, variant_id)
);
create index if not exists idx_branch_stock_variant on public.branch_stock (variant_id);

-- Existing stock belongs to the main branch
insert into public.branch_stock (branch_id, variant_id, qty)
select public.bp_main_branch(), v.id, v.stock_qty from public.product_variants v
where not exists (select 1 from public.branch_stock bs where bs.variant_id = v.id);

/** Stock of a variant in a branch; b = null means all branches (the total). */
create or replace function public.bp_stock(vid bigint, b bigint) returns numeric
language sql stable set search_path = public, pg_temp as $$
  select case when b is null then (select stock_qty from public.product_variants where id = vid)
              else coalesce((select qty from public.branch_stock where variant_id = vid and branch_id = b), 0) end
$$;

-- New products: opening stock goes to the branch that created them
create or replace function public.bp_variant_branch_stock() returns trigger
language plpgsql set search_path = public, pg_temp as $$
begin
  if public.bp_branch() is not null then  -- null only while a backup is being restored
    insert into public.branch_stock (branch_id, variant_id, qty) values (public.bp_branch(), new.id, new.stock_qty)
    on conflict (branch_id, variant_id) do nothing;
  end if;
  return new;
end $$;
drop trigger if exists trg_variant_branch_stock on public.product_variants;
create trigger trg_variant_branch_stock after insert on public.product_variants
  for each row execute function public.bp_variant_branch_stock();

-- ---------------------------------------------------------------------
-- Stock transfers between branches
-- ---------------------------------------------------------------------
create table if not exists public.stock_transfers (
  id             bigint generated by default as identity primary key,
  transfer_no    text not null unique,
  from_branch_id bigint not null references public.branches(id) deferrable initially immediate,
  to_branch_id   bigint not null references public.branches(id) deferrable initially immediate,
  status         text not null default 'in_transit' check (status in ('in_transit','received','cancelled')),
  note           text,
  sent_by        bigint references public.users(id) on delete set null deferrable initially immediate,
  sent_at        timestamp(0) not null default public.bp_now(),
  received_by    bigint references public.users(id) on delete set null deferrable initially immediate,
  received_at    timestamp(0),
  check (from_branch_id <> to_branch_id)
);
create index if not exists idx_transfers_from on public.stock_transfers (from_branch_id);
create index if not exists idx_transfers_to on public.stock_transfers (to_branch_id);
create index if not exists idx_transfers_sent_by on public.stock_transfers (sent_by);
create index if not exists idx_transfers_received_by on public.stock_transfers (received_by);

create table if not exists public.stock_transfer_items (
  id          bigint generated by default as identity primary key,
  transfer_id bigint not null references public.stock_transfers(id) on delete cascade deferrable initially immediate,
  variant_id  bigint not null references public.product_variants(id) deferrable initially immediate,
  qty         numeric(12,2) not null check (qty > 0)
);
create index if not exists idx_sti_transfer on public.stock_transfer_items (transfer_id);
create index if not exists idx_sti_variant on public.stock_transfer_items (variant_id);

-- ---------------------------------------------------------------------
-- branch_id on branch-level records (+ users: which branch they work in;
-- accounts: null = shared by all branches)
-- ---------------------------------------------------------------------
alter table public.users add column if not exists branch_id bigint references public.branches(id) on delete set null deferrable initially immediate;
alter table public.accounts add column if not exists branch_id bigint references public.branches(id) on delete set null deferrable initially immediate;
create index if not exists idx_users_branch on public.users (branch_id);
create index if not exists idx_accounts_branch on public.accounts (branch_id);

create or replace function public.bp_set_branch() returns trigger
language plpgsql set search_path = public, pg_temp as $$
begin
  if new.branch_id is null then new.branch_id := public.bp_branch(); end if;
  return new;
end $$;

do $$
declare t text;
begin
  foreach t in array array['sales','sale_returns','purchases','purchase_returns','expenses','cash_sessions','stock_adjustments',
                           'stock_counts','customer_collections','supplier_payments','purchase_orders','held_invoices'] loop
    execute format('alter table public.%I add column if not exists branch_id bigint references public.branches(id) deferrable initially immediate', t);
    execute format('update public.%I set branch_id = public.bp_main_branch() where branch_id is null', t);
    execute format('create index if not exists idx_%1$s_branch on public.%1$I (branch_id)', t);
    execute format('drop trigger if exists trg_%1$s_branch on public.%1$I', t);
    execute format('create trigger trg_%1$s_branch before insert on public.%1$I for each row execute function public.bp_set_branch()', t);
  end loop;
end $$;

/** After restoring an older backup: give unbranched rows and stock to the main branch. */
create or replace function public.bp_branch_backfill() returns void
language plpgsql set search_path = public, pg_temp as $$
declare t text;
begin
  if not exists (select 1 from public.branches) then
    insert into public.branches (name, code, is_main) values ('Main Branch', 'MAIN', true);
  end if;
  foreach t in array array['sales','sale_returns','purchases','purchase_returns','expenses','cash_sessions','stock_adjustments',
                           'stock_counts','customer_collections','supplier_payments','purchase_orders','held_invoices'] loop
    execute format('update public.%I set branch_id = public.bp_main_branch() where branch_id is null', t);
  end loop;
  insert into public.branch_stock (branch_id, variant_id, qty)
  select public.bp_main_branch(), v.id, v.stock_qty from public.product_variants v
  where not exists (select 1 from public.branch_stock bs where bs.variant_id = v.id);
end $$;

do $$
declare t text;
begin
  foreach t in array array['branches','branch_stock','stock_transfers','stock_transfer_items'] loop
    execute format('alter table public.%I enable row level security', t);
    if exists (select 1 from pg_roles where rolname = 'anon') then
      execute format('revoke all on public.%I from anon, authenticated', t);
    end if;
  end loop;
  if exists (select 1 from pg_roles where rolname = 'anon') then
    revoke execute on function public.bp_main_branch(), public.bp_branch(), public.bp_stock(bigint, bigint),
      public.bp_variant_branch_stock(), public.bp_set_branch(), public.bp_branch_backfill() from anon, authenticated, public;
  end if;
end $$;
